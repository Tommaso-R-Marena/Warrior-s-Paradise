"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const js=fs.readFileSync(path.resolve(__dirname,"../../browser/3d/ww2-vehicles.js"),"utf8");
const root={};vm.runInNewContext(js,{window:root,Math});
const fleet=root.WPArmoredFleet;
assert.equal(fleet.info().vehicles.length,3);
const player={x:-36,z:-33,yaw:0,hp:100};
assert(!fleet.toggle(player,()=>false),"Remote entry allowed");
player.x=-41;player.z=-31;
assert(fleet.toggle(player,()=>false),"GAZ-67 entry failed");
assert.equal(fleet.info().driving,"jeep");
const input={keys:{KeyW:true},joyY:0,joyX:0};
for(let i=0;i<90;i++)fleet.move(1/60,input,player,()=>false);
assert(fleet.current().speed>3,"Engine must accelerate");
assert(Math.hypot(player.x+41,player.z+31)>1.2,"Jeep must actually drive");
assert(fleet.toggle(player,()=>false),"Exit must work");
fleet.reset();player.x=-40;player.z=-23;
assert(fleet.toggle(player,()=>false),"Tank entry failed");
const target={x:-40-Math.sin(.5)*20,z:-23+Math.cos(.5)*20,hp:300};
let blasts=0;
assert(fleet.fire(player,[target],()=>true,()=>{},()=>{},()=>{blasts++}));
assert(target.hp<300,"Cannon should hit aligned defender");
assert(!fleet.fire(player,[target],()=>true),"Cannon reload missing");
assert.equal(blasts,1);
fleet.tick(3.5,player,()=>false,()=>{},()=>{});
assert(fleet.fire(player,[target],()=>true),"Cannon cannot fire after reload");
fleet.reset();
fleet.draw({tri(){},box(){},cone(){}},null,"low",player,0);
assert(fleet.info().renderedTriangles>0,"Low graphics vehicles missing");
console.log("PASS WW2 vehicles: entry, driving, ballistic firing, reload and render fallback");
