"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const source=fs.readFileSync(path.resolve(__dirname,"../../browser/3d/ww2-vehicles.js"),"utf8");
const window={};vm.runInNewContext(source,{window,Math,Number,Set},{filename:"ww2-vehicles.js"});
const fleet=window.WPArmoredFleet;
const world={heightAt:()=>0,blocked:()=>false,traversable:()=>true,obstacles:[]};
function player(){return {x:0,z:0,yaw:0,pitch:0,hp:100};}
let p=player();
assert(fleet.mount(p,"armor"),"Cannot deploy directly in the Sherman");
assert.equal(fleet.current().id,"armor");
assert.equal(fleet.current().ammo.ap,16);
assert.equal(fleet.current().ammo.he,8);
const initial=fleet.current(),start={x:initial.x,z:initial.z,yaw:initial.yaw};
for(let i=0;i<120;i++)fleet.move(1/60,{keys:{KeyD:true}},p,()=>false,()=>true);
assert(Math.abs(fleet.current().yaw-start.yaw)>.05,"Tank must pivot steer even at zero speed");
for(let i=0;i<180;i++)fleet.move(1/60,{keys:{KeyW:true}},p,()=>false,()=>true);
assert(Math.hypot(p.x-start.x,p.z-start.z)>3,"Sherman must physically drive on its tracks");
assert(fleet.current().speed>0,"Tank engine never accelerated");
assert.equal(fleet.info().driving,"armor");
fleet.reset();
p=player();assert(fleet.mount(p,"armor"));
const tank=fleet.current(),yaw=tank.yaw; p.yaw=yaw;p.pitch=0;
const e={x:tank.x-Math.sin(yaw)*15,z:tank.z+Math.cos(yaw)*15,hp:180,groundY:0,hit:0,suppression:0};
let impacts=0,hits=0;
assert(fleet.fire(p,[e],()=>true,()=>{hits++},()=>{},()=>{impacts++},world));
assert(e.hp<180&&hits===1&&impacts===1,"Live trajectory should strike aligned infantry");
assert.equal(fleet.info().vehicles.find(v=>v.id==="armor").ammo.ap,15,"AP ammunition must decrement");
assert(fleet.info().activeShells>0,"Shell streak needs active time-based presentation");
assert(!fleet.fire(p,[e],()=>true,null,null,null,world),"Reload cooldown must reject immediate second cannon shot");
fleet.tick(3.6,p,()=>false,()=>{},()=>{},world);
assert(fleet.selectShell("he"),"Shell switching failed");
assert.equal(fleet.current().shellType,"he");
const e2={x:e.x,z:e.z,hp:140,groundY:0,hit:0};
assert(fleet.fire(p,[e2],()=>true,()=>{},()=>{},()=>{},world));
assert(e2.hp<140,"HE shell must injure nearby soldiers");
assert.equal(fleet.current().ammo.he,7);
fleet.reset();p=player();assert(fleet.mount(p,"armor"));p.yaw=fleet.current().yaw;p.pitch=0;
const sx=fleet.current().x,sz=fleet.current().z,dx=-Math.sin(p.yaw),dz=Math.cos(p.yaw);
const blockedEnemy={x:sx+dx*19,z:sz+dz*19,hp:120,groundY:0};
const cover={heightAt:()=>0,blocked:()=>false,traversable:()=>true,obstacles:[
 [sx+dx*9,sz+dz*9,3,3,3,0]
]};
assert(fleet.fire(p,[blockedEnemy],()=>true,()=>{},()=>{},()=>{},cover));
assert.equal(blockedEnemy.hp,120,"A shell must not shoot through a stone barrier");
assert.equal(fleet.current().lastImpact.type,"cover");
fleet.reset();p=player();assert(fleet.mount(p,"armor"));
const friendly=fleet.current(),enemy=fleet.info().vehicles.find(v=>v.id==="enemy");
friendly.x=enemy.x-20;friendly.z=enemy.z;friendly.groundY=0;
p.x=friendly.x;p.z=friendly.z;p.yaw=-Math.PI/2;p.pitch=0;
assert(fleet.fire(p,[],()=>true,()=>{},()=>{},()=>{},world),"The main cannon could not engage enemy armor");
const after=fleet.info().vehicles.find(v=>v.id==="enemy");
assert(after.hp<enemy.hp&&after.alive,"AP projectile should damage enemy tank");
assert.equal(friendly.lastImpact.type,"armor");
fleet.reset();
const movingPlayer={x:8,z:15,yaw:0,hp:100};
const before=fleet.info().vehicles.find(v=>v.id==="enemy");
for(let i=0;i<680;i++)fleet.tick(1/60,movingPlayer,()=>false,()=>{},()=>{},world);
const advanced=fleet.info().vehicles.find(v=>v.id==="enemy");
assert(Math.hypot(advanced.x-before.x,advanced.z-before.z)>.45,"Panzer AI stayed immobile");
assert(Math.hypot(advanced.x-movingPlayer.x,advanced.z-movingPlayer.z)<
 Math.hypot(before.x-movingPlayer.x,before.z-movingPlayer.z),
 "Panzer failed to advance toward the player");
fleet.reset();p=player();fleet.mount(p,"armor");
const origin=fleet.current(),firstX=origin.x,firstZ=origin.z;
for(let i=0;i<180;i++)fleet.move(1/60,{keys:{KeyW:true}},p,(x,z,r)=>z>firstZ+1.0,()=>true);
assert(fleet.info().collisionRejected>0,"Tank swept collision should stop a physical obstacle");
assert(Math.hypot(origin.x-firstX,origin.z-firstZ)<2,"Tank tunneled through a blocking line");
const sourceGame=fs.readFileSync(path.resolve(__dirname,"../../browser/3d/game.js"),"utf8");
const html=fs.readFileSync(path.resolve(__dirname,"../../browser/3d/index.html"),"utf8");
assert(html.includes('id="deployment"'));
assert(sourceGame.includes('window.WPArmoredFleet.mount(player,"armor")'));
assert(sourceGame.includes('fleet.fire(player,game.enemies,lineHit'));
console.log("PASS mobile/desktop tank physics, turret, AP/HE, shell cover, enemy armor, reload, Panzer advance");
